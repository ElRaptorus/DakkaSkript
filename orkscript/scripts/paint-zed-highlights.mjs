import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const TYPE_PRIMITIVE_TYPESCRIPT = new Set(['number', 'string', 'boolean']);
const TYPE_CONSTRUCTOR_TYPESCRIPT = new Set(['Promise', 'Error', 'Array', 'Object', 'Record']);
const SACRED_IDENTIFIERS = ['waaagh', 'GetDeffGun', 'Dakka'];

const NVIM_ONLY_PATTERNS = [
  `((identifier) @variable.builtin
 (#match? @variable.builtin "^(arguments|module|console|window|document)$")
 (#is-not? local))`,
  `((identifier) @function.builtin
 (#eq? @function.builtin "require")
 (#is-not? local))`,
];

function ensureTrailingNewline(text) {
  return text.endsWith('\n') ? text : `${text}\n`;
}

function stripNvimOnlyPredicates(javascriptHighlights) {
  let stripped = javascriptHighlights;
  for (const pattern of NVIM_ONLY_PATTERNS) {
    if (!stripped.includes(pattern)) {
      throw new Error(
        `Vendored tree-sitter-javascript highlights.scm is missing expected nvim-only pattern:\n${pattern}`,
      );
    }
    stripped = stripped.replace(pattern, '');
  }
  if (stripped.includes('#is-not?')) {
    throw new Error('Vendored JavaScript highlights still contain #is-not? after stripping');
  }
  return stripped;
}

function formatAnyOfQuery(nodeType, captureName, words) {
  const quotedWords = words.map((word) => `    "${word}"`).join('\n');
  return `((${nodeType}) @${captureName}
  (#any-of? @${captureName}
${quotedWords}
  ))
`;
}

function classifyDictionary(dictionary) {
  const keywordWords = [];
  const primitiveTypeWords = [];
  const constructorWords = [];

  for (const [orkWord, typescriptToken] of Object.entries(dictionary)) {
    if (SACRED_IDENTIFIERS.includes(orkWord)) {
      throw new Error(`dictionary.json must not contain sacred identifier ${orkWord}`);
    }
    if (TYPE_PRIMITIVE_TYPESCRIPT.has(typescriptToken)) {
      primitiveTypeWords.push(orkWord);
    } else if (TYPE_CONSTRUCTOR_TYPESCRIPT.has(typescriptToken)) {
      constructorWords.push(orkWord);
    } else {
      keywordWords.push(orkWord);
    }
  }

  return { keywordWords, primitiveTypeWords, constructorWords };
}

function buildDictionaryPredicates(dictionary) {
  const { keywordWords, primitiveTypeWords, constructorWords } = classifyDictionary(dictionary);
  const typeIdentifierWords = [...primitiveTypeWords, ...constructorWords];
  const paintedWords = new Set([...keywordWords, ...primitiveTypeWords, ...constructorWords]);

  for (const orkWord of Object.keys(dictionary)) {
    if (!paintedWords.has(orkWord)) {
      throw new Error(`dictionary key ${orkWord} was not classified into a highlights.scm list`);
    }
  }

  const sections = [
    '; Orkscript dictionary identifiers (generated from orkscript/dictionary.json)',
    '',
    formatAnyOfQuery('identifier', 'keyword', keywordWords),
    formatAnyOfQuery('identifier', 'type', primitiveTypeWords),
    formatAnyOfQuery('type_identifier', 'type', typeIdentifierWords),
    formatAnyOfQuery('identifier', 'constructor', constructorWords),
  ];

  const predicates = sections.join('\n');
  for (const sacredIdentifier of SACRED_IDENTIFIERS) {
    if (predicates.includes(`"${sacredIdentifier}"`)) {
      throw new Error(`${sacredIdentifier} must not appear in dictionary any-of lists`);
    }
  }
  return predicates;
}

export function writeZedHighlights(repoRoot, dictionary) {
  const typescriptHighlightsPath = join(
    repoRoot,
    'editors/zed/vendor/tree-sitter-typescript-highlights.scm',
  );
  const javascriptHighlightsPath = join(
    repoRoot,
    'editors/zed/vendor/tree-sitter-javascript-highlights.scm',
  );
  const outputHighlightsPath = join(repoRoot, 'editors/zed/languages/orkscript/highlights.scm');

  const typescriptHighlights = ensureTrailingNewline(readFileSync(typescriptHighlightsPath, 'utf8'));
  const javascriptHighlights = stripNvimOnlyPredicates(
    ensureTrailingNewline(readFileSync(javascriptHighlightsPath, 'utf8')),
  );
  const dictionaryPredicates = buildDictionaryPredicates(dictionary);

  const generated = [
    '; Generated by orkscript/scripts/paint-grammar.mjs. Do not edit by hand.',
    '; tree-sitter-typescript queries/highlights.scm @ f975a621f4e7f532fe322e13c4f79495e0a7b2e7 (v0.23.2)',
    '; tree-sitter-javascript queries/highlights.scm @ 3a837b6f3658ca3618f2022f8707e29739c91364 (v0.23.1, ecma inherit)',
    '',
    typescriptHighlights.trimEnd(),
    '',
    javascriptHighlights.trimEnd(),
    '',
    dictionaryPredicates.trimEnd(),
    '',
  ].join('\n');

  mkdirSync(dirname(outputHighlightsPath), { recursive: true });
  writeFileSync(outputHighlightsPath, generated);
}
